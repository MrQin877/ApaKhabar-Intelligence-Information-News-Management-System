import { Head, router, usePage } from '@inertiajs/react';
import {
    Archive,
    Bot,
    FileText,
    FolderSearch,
    LoaderCircle,
    Paperclip,
    Send,
    Sparkles,
    X,
} from 'lucide-react';
import React, { useEffect, useMemo, useRef, useState } from 'react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card, CardContent, CardHeader, CardTitle } from '@/components/ui/card';
import { Checkbox } from '@/components/ui/checkbox';
import {
    Dialog,
    DialogContent,
    DialogDescription,
    DialogHeader,
    DialogTitle,
    DialogTrigger,
} from '@/components/ui/dialog';
import { Input } from '@/components/ui/input';
import {
    MessageScroller,
    MessageScrollerButton,
    MessageScrollerContent,
    MessageScrollerItem,
    MessageScrollerProvider,
    MessageScrollerViewport,
} from '@/components/ui/message-scroller';
import { Tabs, TabsContent, TabsList, TabsTrigger } from '@/components/ui/tabs';
import { Textarea } from '@/components/ui/textarea';
import AppLayout from '@/layouts/app-layout';
import creatorRoutes from '@/routes/admin/creator';
import type { BreadcrumbItem } from '@/types';

interface InformationItem {
    id: number;
    document_id: number;
    title: string;
    summary: string;
    labels: string[];
    document: { id: number; original_name: string };
}
interface DocumentItem {
    id: number;
    original_name: string;
    status: string;
}
interface MissingQuestion {
    field: string;
    importance: 'required' | 'recommended';
    question: string;
    reason?: string | null;
}
interface NewsSession {
    id: number;
    prompt: string | null;
    selected_document_ids: number[];
    selected_information_ids: number[];
    pending_questions: MissingQuestion[];
    conflicts: string[];
}
interface Evidence {
    source: string;
    quote: string;
}
interface Article {
    draft_id: number;
    headline: string;
    subheadline: string | null;
    lead: string;
    body: string[];
    labels: string[];
    warnings: string[];
    selected_sources: Array<{
        id: number;
        title: string;
        document: string;
        evidence: Evidence[];
    }>;
}
interface Recommendation {
    document_id: number;
    name: string;
    source: string;
    excerpt: string;
    distance: number | null;
}
interface Props {
    informationItems: InformationItem[];
    documents: DocumentItem[];
    generatedArticle?: Article | null;
    newsSession?: NewsSession | null;
    preselectedInformationIds?: number[];
    initialDocumentIds?: number[];
    initialPrompt?: string | null;
    initialManualFact?: string | null;
    autoGenerate?: boolean;
}

const breadcrumbs: BreadcrumbItem[] = [
    { title: 'Intelligent News Creator', href: creatorRoutes.create() },
];

export default function NewsCreatorAgent({
    informationItems,
    documents,
    generatedArticle,
    newsSession,
    preselectedInformationIds = [],
    initialDocumentIds = [],
    initialPrompt = '',
    initialManualFact = '',
    autoGenerate = false,
}: Props) {
    const errors = (usePage().props.errors ?? {}) as Record<string, string>;
    const fileInput = useRef<HTMLInputElement>(null);
    const autoGenerated = useRef(false);
    const [prompt, setPrompt] = useState(
        initialPrompt ?? newsSession?.prompt ?? '',
    );
    const [files, setFiles] = useState<File[]>([]);
    const [manualFact, setManualFact] = useState(initialManualFact ?? '');
    const [informationIds, setInformationIds] = useState(
        newsSession?.selected_information_ids ?? preselectedInformationIds,
    );
    const [documentIds, setDocumentIds] = useState(
        newsSession?.selected_document_ids ?? initialDocumentIds,
    );
    const [answers, setAnswers] = useState<Record<string, string>>({});
    const [busy, setBusy] = useState(false);
    const [picker, setPicker] = useState(false);
    const [query, setQuery] = useState('');
    const [recommendations, setRecommendations] = useState<Recommendation[]>(
        [],
    );
    const [findingRelated, setFindingRelated] = useState(false);
    const questions = newsSession?.pending_questions ?? [];
    const hasSources = informationIds.length > 0 || documentIds.length > 0;
    const shownInformation = useMemo(() => {
        const needle = query.trim().toLocaleLowerCase('id');

        return needle
            ? informationItems.filter((item) =>
                  [
                      item.title,
                      item.summary,
                      item.document.original_name,
                      ...item.labels,
                  ]
                      .join(' ')
                      .toLocaleLowerCase('id')
                      .includes(needle),
              )
            : informationItems;
    }, [informationItems, query]);
    const actions = generatedArticle
        ? ['Ringkas draf', 'Ubah judul', 'Buat nada lebih formal']
        : questions.length
          ? ['Lengkapi informasi yang hilang', 'Tinjau kembali sumber']
          : hasSources || files.length
            ? [
                  'Buat draf berita',
                  'Gabungkan informasi terkait',
                  'Buat pengumuman',
              ]
            : ['Buat draf berita', 'Pilih sumber informasi', 'Unggah dokumen'];

    const toggle = (
        values: number[],
        id: number,
        setter: (ids: number[]) => void,
    ) =>
        setter(
            values.includes(id)
                ? values.filter((value) => value !== id)
                : [...values, id],
        );
    function addFiles(list: FileList | null) {
        if (!list) {
            return;
        }

        const incoming = Array.from(list);

        if (files.length + incoming.length > 5) {
            window.alert('Maksimum lima dokumen untuk setiap permintaan.');

            return;
        }

        setFiles((current) => [...current, ...incoming]);
    }
    function submit() {
        if (files.length) {
            const data = new FormData();
            files.forEach((file) => data.append('documents[]', file));

            if (prompt.trim()) {
                data.append('prompt', prompt.trim());
            }

            if (manualFact.trim()) {
                data.append('manual_fact', manualFact.trim());
            }

            informationIds.forEach((id) =>
                data.append('information_ids[]', String(id)),
            );
            documentIds.forEach((id) =>
                data.append('document_ids[]', String(id)),
            );

            setBusy(true);
            router.post('/admin/apakhabar-creator/documents', data, {
                forceFormData: true,
                onFinish: () => setBusy(false),
            });

            return;
        }

        setBusy(true);
        router.post(
            '/admin/apakhabar-creator/generate',
            {
                session_id: newsSession?.id ?? null,
                information_ids: informationIds,
                document_ids: documentIds,
                prompt: prompt.trim() || null,
                answers: manualFact.trim()
                    ? { ...answers, additional_context: manualFact.trim() }
                    : answers,
                tone: 'formal',
            },
            { onFinish: () => setBusy(false) },
        );
    }
    async function findRelated() {
        if (!prompt.trim()) {
            return;
        }

        setFindingRelated(true);

        try {
            const token =
                document.querySelector<HTMLMetaElement>(
                    'meta[name="csrf-token"]',
                )?.content ?? '';
            const response = await fetch(
                '/admin/apakhabar-creator/recommendations',
                {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json',
                        Accept: 'application/json',
                        'X-CSRF-TOKEN': token,
                    },
                    body: JSON.stringify({ query: prompt.trim() }),
                },
            );
            const data = (await response.json()) as {
                recommendations?: Recommendation[];
            };
            setRecommendations(data.recommendations ?? []);
        } finally {
            setFindingRelated(false);
        }
    }
    useEffect(() => {
        if (
            !autoGenerate ||
            autoGenerated.current ||
            !preselectedInformationIds.length
        ) {
            return;
        }

        autoGenerated.current = true;
        setBusy(true);
        router.post(
            '/admin/apakhabar-creator/generate',
            {
                information_ids: preselectedInformationIds,
                document_ids: initialDocumentIds,
                prompt: initialPrompt || null,
                answers: initialManualFact
                    ? { additional_context: initialManualFact }
                    : {},
                tone: 'formal',
            },
            { onFinish: () => setBusy(false) },
        );
    }, [
        autoGenerate,
        initialDocumentIds,
        initialPrompt,
        initialManualFact,
        preselectedInformationIds,
    ]);

    return (
        <>
            <Head title="Intelligent News Creator" />
            <div className="dark flex h-[calc(100vh-4rem)] min-h-[640px] flex-col overflow-hidden bg-background text-foreground lg:flex-row">
                <section className="flex min-h-0 flex-1 flex-col border-b bg-background lg:w-[42%] lg:max-w-[620px] lg:border-r lg:border-b-0">
                    <header className="flex shrink-0 items-center justify-between border-b px-5 py-4">
                        <div className="flex items-center gap-3">
                            <div className="flex size-9 items-center justify-center rounded-lg bg-primary text-primary-foreground">
                                <Bot className="size-5" />
                            </div>
                            <div>
                                <h1 className="font-semibold">
                                    Asisten Berita AI
                                </h1>
                                <p className="text-xs text-muted-foreground">
                                    Sumber dikendalikan moderator
                                </p>
                            </div>
                        </div>
                        <Button
                            variant="outline"
                            size="sm"
                            onClick={() =>
                                router.visit(creatorRoutes.archive())
                            }
                        >
                            <Archive /> Arsip
                        </Button>
                    </header>
                    <MessageScrollerProvider
                        autoScroll
                        defaultScrollPosition="end"
                    >
                        <MessageScroller className="min-h-0 flex-1">
                            <MessageScrollerViewport className="px-5 py-5">
                                <MessageScrollerContent className="gap-4">
                                    <MessageScrollerItem messageId="welcome">
                                        <div className="max-w-[88%] rounded-xl border bg-muted/50 p-4 text-sm leading-6">
                                            Pilih informasi atau dokumen
                                            tersimpan, atau lampirkan hingga
                                            lima file baru. Saya akan memeriksa
                                            kelengkapan sebelum membuat draf.
                                        </div>
                                    </MessageScrollerItem>
                                    {hasSources && (
                                        <MessageScrollerItem messageId="sources">
                                            <div className="ml-auto max-w-[88%] rounded-xl bg-primary p-4 text-sm text-primary-foreground">
                                                Gunakan {informationIds.length}{' '}
                                                informasi dan{' '}
                                                {documentIds.length} dokumen
                                                yang saya setujui.
                                            </div>
                                        </MessageScrollerItem>
                                    )}
                                    {questions.map((question) => (
                                        <MessageScrollerItem
                                            key={question.field}
                                            messageId={`q-${question.field}`}
                                        >
                                            <Card className="max-w-[92%] gap-3 border-warning-border bg-warning-bg py-4 shadow-none">
                                                <CardHeader className="gap-1 px-4">
                                                    <Badge
                                                        variant="outline"
                                                        className="w-fit border-warning-border text-warning-text"
                                                    >
                                                        Informasi diperlukan
                                                    </Badge>
                                                    <CardTitle className="text-sm text-warning-text">
                                                        {question.question}
                                                    </CardTitle>
                                                    {question.reason && (
                                                        <p className="text-xs text-warning-text/80">
                                                            {question.reason}
                                                        </p>
                                                    )}
                                                </CardHeader>
                                                <CardContent className="px-4">
                                                    <Input
                                                        value={
                                                            answers[
                                                                question.field
                                                            ] ?? ''
                                                        }
                                                        onChange={(event) =>
                                                            setAnswers(
                                                                (current) => ({
                                                                    ...current,
                                                                    [question.field]:
                                                                        event
                                                                            .target
                                                                            .value,
                                                                }),
                                                            )
                                                        }
                                                        placeholder="Masukkan fakta yang benar…"
                                                    />
                                                </CardContent>
                                            </Card>
                                        </MessageScrollerItem>
                                    ))}
                                    {recommendations.length > 0 && (
                                        <MessageScrollerItem messageId="recommendations">
                                            <Card className="max-w-[92%] gap-3 py-4 shadow-none">
                                                <CardHeader className="px-4">
                                                    <CardTitle className="text-sm">
                                                        Rekomendasi informasi
                                                        terkait
                                                    </CardTitle>
                                                    <p className="text-xs text-muted-foreground">
                                                        Tinjau dan setujui
                                                        sebelum sumber
                                                        digunakan.
                                                    </p>
                                                </CardHeader>
                                                <CardContent className="space-y-2 px-4">
                                                    {recommendations.map(
                                                        (item) => (
                                                            <div
                                                                key={
                                                                    item.document_id
                                                                }
                                                                className="rounded-lg border p-3"
                                                            >
                                                                <p className="text-sm font-medium">
                                                                    {item.name}
                                                                </p>
                                                                <p className="line-clamp-2 text-xs text-muted-foreground">
                                                                    {
                                                                        item.excerpt
                                                                    }
                                                                </p>
                                                                <Button
                                                                    className="mt-2"
                                                                    variant={
                                                                        documentIds.includes(
                                                                            item.document_id,
                                                                        )
                                                                            ? 'secondary'
                                                                            : 'outline'
                                                                    }
                                                                    size="xs"
                                                                    onClick={() =>
                                                                        toggle(
                                                                            documentIds,
                                                                            item.document_id,
                                                                            setDocumentIds,
                                                                        )
                                                                    }
                                                                >
                                                                    {documentIds.includes(
                                                                        item.document_id,
                                                                    )
                                                                        ? 'Disetujui'
                                                                        : 'Setujui sumber'}
                                                                </Button>
                                                            </div>
                                                        ),
                                                    )}
                                                </CardContent>
                                            </Card>
                                        </MessageScrollerItem>
                                    )}
                                    {generatedArticle && (
                                        <MessageScrollerItem
                                            messageId="done"
                                            scrollAnchor
                                        >
                                            <div className="max-w-[88%] rounded-xl border border-success-border bg-success-bg p-4 text-sm text-success-text">
                                                Draf telah dibuat. Tinjau
                                                artikel dan bukti sebelum
                                                publikasi.
                                            </div>
                                        </MessageScrollerItem>
                                    )}
                                </MessageScrollerContent>
                            </MessageScrollerViewport>
                            <MessageScrollerButton />
                        </MessageScroller>
                    </MessageScrollerProvider>
                    <div className="shrink-0 space-y-3 border-t bg-background p-4">
                        <div className="flex gap-2 overflow-x-auto pb-1">
                            {actions.map((action) => (
                                <Button
                                    key={action}
                                    variant="outline"
                                    size="sm"
                                    className="rounded-full"
                                    onClick={() => setPrompt(action)}
                                >
                                    {action}
                                </Button>
                            ))}
                            {prompt.trim() && (
                                <Button
                                    variant="outline"
                                    size="sm"
                                    className="rounded-full"
                                    disabled={findingRelated}
                                    onClick={findRelated}
                                >
                                    {findingRelated ? (
                                        <LoaderCircle className="animate-spin" />
                                    ) : (
                                        <Sparkles />
                                    )}
                                    Cari informasi terkait
                                </Button>
                            )}
                        </div>
                        {(files.length > 0 || hasSources) && (
                            <div className="flex flex-wrap gap-2">
                                {files.map((file, index) => (
                                    <Badge
                                        key={`${file.name}-${index}`}
                                        variant="secondary"
                                        className="gap-1 py-1.5"
                                    >
                                        <Paperclip className="size-3" />
                                        {file.name}
                                        <button
                                            type="button"
                                            onClick={() =>
                                                setFiles((current) =>
                                                    current.filter(
                                                        (_, position) =>
                                                            position !== index,
                                                    ),
                                                )
                                            }
                                        >
                                            <X className="size-3" />
                                        </button>
                                    </Badge>
                                ))}
                                {informationIds.length > 0 && (
                                    <Badge variant="secondary">
                                        {informationIds.length} informasi
                                    </Badge>
                                )}
                                {documentIds.length > 0 && (
                                    <Badge variant="secondary">
                                        {documentIds.length} dokumen
                                    </Badge>
                                )}
                            </div>
                        )}
                        <div className="rounded-xl border bg-background p-2 shadow-sm focus-within:ring-2 focus-within:ring-ring/30">
                            <Textarea
                                value={prompt}
                                onChange={(event) =>
                                    setPrompt(event.target.value)
                                }
                                placeholder="Jelaskan berita yang ingin dibuat atau tambahkan arahan editorial…"
                                className="min-h-20 resize-none border-0 bg-transparent shadow-none focus-visible:ring-0"
                            />
                            <div className="flex items-center justify-between border-t pt-2">
                                <div className="flex gap-1">
                                    <input
                                        ref={fileInput}
                                        type="file"
                                        multiple
                                        className="hidden"
                                        accept=".pdf,.docx,.xlsx,.xlsm,.csv,.txt,.jpg,.jpeg,.png"
                                        onChange={(event) => {
                                            addFiles(event.target.files);
                                            event.target.value = '';
                                        }}
                                    />
                                    <Button
                                        variant="ghost"
                                        size="icon-sm"
                                        onClick={() =>
                                            fileInput.current?.click()
                                        }
                                        title="Unggah file"
                                    >
                                        <Paperclip />
                                    </Button>
                                    <Dialog
                                        open={picker}
                                        onOpenChange={setPicker}
                                    >
                                        <DialogTrigger asChild>
                                            <Button
                                                variant="ghost"
                                                size="icon-sm"
                                                title="Pilih sumber"
                                            >
                                                <FolderSearch />
                                            </Button>
                                        </DialogTrigger>
                                        <DialogContent className="max-h-[80vh] sm:max-w-2xl">
                                            <DialogHeader>
                                                <DialogTitle>
                                                    Pilih sumber yang disetujui
                                                </DialogTitle>
                                                <DialogDescription>
                                                    Hanya sumber terpilih yang
                                                    dipakai untuk membuat
                                                    berita.
                                                </DialogDescription>
                                            </DialogHeader>
                                            <Input
                                                value={query}
                                                onChange={(event) =>
                                                    setQuery(event.target.value)
                                                }
                                                placeholder="Cari sumber…"
                                            />
                                            <Tabs defaultValue="information">
                                                <TabsList>
                                                    <TabsTrigger value="information">
                                                        Informasi
                                                    </TabsTrigger>
                                                    <TabsTrigger value="documents">
                                                        Dokumen
                                                    </TabsTrigger>
                                                    <TabsTrigger value="manual">
                                                        Fakta manual
                                                    </TabsTrigger>
                                                </TabsList>
                                                <TabsContent
                                                    value="information"
                                                    className="max-h-[48vh] space-y-2 overflow-y-auto"
                                                >
                                                    {shownInformation.map(
                                                        (item) => (
                                                            <label
                                                                key={item.id}
                                                                className="flex cursor-pointer gap-3 rounded-lg border p-3 hover:bg-muted/50"
                                                            >
                                                                <Checkbox
                                                                    checked={informationIds.includes(
                                                                        item.id,
                                                                    )}
                                                                    onCheckedChange={() =>
                                                                        toggle(
                                                                            informationIds,
                                                                            item.id,
                                                                            setInformationIds,
                                                                        )
                                                                    }
                                                                />
                                                                <span>
                                                                    <span className="block text-sm font-medium">
                                                                        {
                                                                            item.title
                                                                        }
                                                                    </span>
                                                                    <span className="line-clamp-2 text-xs text-muted-foreground">
                                                                        {
                                                                            item.summary
                                                                        }
                                                                    </span>
                                                                    <span className="text-xs text-primary">
                                                                        {
                                                                            item
                                                                                .document
                                                                                .original_name
                                                                        }
                                                                    </span>
                                                                </span>
                                                            </label>
                                                        ),
                                                    )}
                                                </TabsContent>
                                                <TabsContent
                                                    value="documents"
                                                    className="max-h-[48vh] space-y-2 overflow-y-auto"
                                                >
                                                    {documents.map(
                                                        (document) => (
                                                            <label
                                                                key={
                                                                    document.id
                                                                }
                                                                className="flex cursor-pointer items-center gap-3 rounded-lg border p-3 hover:bg-muted/50"
                                                            >
                                                                <Checkbox
                                                                    checked={documentIds.includes(
                                                                        document.id,
                                                                    )}
                                                                    onCheckedChange={() =>
                                                                        toggle(
                                                                            documentIds,
                                                                            document.id,
                                                                            setDocumentIds,
                                                                        )
                                                                    }
                                                                />
                                                                <FileText className="size-4" />
                                                                <span className="text-sm font-medium">
                                                                    {
                                                                        document.original_name
                                                                    }
                                                                </span>
                                                            </label>
                                                        ),
                                                    )}
                                                </TabsContent>
                                                <TabsContent value="manual">
                                                    <div className="space-y-2 rounded-lg border p-3">
                                                        <p className="text-sm font-medium">
                                                            Fakta yang diberikan
                                                            moderator
                                                        </p>
                                                        <p className="text-xs text-muted-foreground">
                                                            Fakta ini akan
                                                            ditandai sebagai
                                                            user-provided dan
                                                            tidak dianggap
                                                            berasal dari
                                                            dokumen.
                                                        </p>
                                                        <Textarea
                                                            value={manualFact}
                                                            onChange={(event) =>
                                                                setManualFact(
                                                                    event.target
                                                                        .value,
                                                                )
                                                            }
                                                            placeholder="Contoh: Kegiatan akan berlangsung pada 20 September 2026."
                                                        />
                                                    </div>
                                                </TabsContent>
                                            </Tabs>
                                            <Button
                                                onClick={() => setPicker(false)}
                                            >
                                                Gunakan sumber terpilih
                                            </Button>
                                        </DialogContent>
                                    </Dialog>
                                </div>
                                <Button
                                    size="icon"
                                    disabled={
                                        busy ||
                                        (!files.length &&
                                            !hasSources &&
                                            !newsSession &&
                                            !prompt.trim() &&
                                            !manualFact.trim())
                                    }
                                    onClick={submit}
                                >
                                    {busy ? (
                                        <LoaderCircle className="animate-spin" />
                                    ) : (
                                        <Send />
                                    )}
                                </Button>
                            </div>
                        </div>
                        {(errors.document ||
                            errors.documents ||
                            errors.generation) && (
                            <p className="text-sm text-danger-text">
                                {errors.document ||
                                    errors.documents ||
                                    errors.generation}
                            </p>
                        )}
                        <p className="text-xs text-muted-foreground">
                            Maksimum 5 file baru · dokumen, spreadsheet, teks,
                            dan gambar OCR
                        </p>
                    </div>
                </section>
                <section className="min-h-0 flex-1 overflow-y-auto bg-background p-5 lg:p-8">
                    {generatedArticle ? (
                        <article className="mx-auto max-w-3xl rounded-xl border bg-card p-6 shadow-sm md:p-10">
                            <div className="mb-5 flex flex-wrap gap-2">
                                <Badge className="bg-success-bg text-success-text">
                                    Draf AI
                                </Badge>
                                {generatedArticle.labels.map((label) => (
                                    <Badge key={label} variant="secondary">
                                        {label}
                                    </Badge>
                                ))}
                            </div>
                            <h2 className="text-3xl leading-tight font-semibold">
                                {generatedArticle.headline}
                            </h2>
                            {generatedArticle.subheadline && (
                                <p className="mt-3 text-lg text-muted-foreground">
                                    {generatedArticle.subheadline}
                                </p>
                            )}
                            <div className="my-6 h-px bg-border" />
                            <p className="text-lg leading-8 font-medium">
                                {generatedArticle.lead}
                            </p>
                            <div className="mt-5 space-y-5 leading-8">
                                {generatedArticle.body.map(
                                    (paragraph, index) => (
                                        <p key={index}>{paragraph}</p>
                                    ),
                                )}
                            </div>
                            <div className="mt-8 border-t pt-6">
                                <h3 className="mb-3 text-sm font-semibold">
                                    Sumber yang digunakan
                                </h3>
                                {generatedArticle.selected_sources.map(
                                    (source) => (
                                        <div
                                            key={source.id}
                                            className="mb-2 rounded-lg border bg-muted/30 p-3"
                                        >
                                            <p className="text-sm font-medium">
                                                {source.title}
                                            </p>
                                            <p className="text-xs text-muted-foreground">
                                                {source.document}
                                            </p>
                                            {source.evidence.map(
                                                (evidence, index) => (
                                                    <p
                                                        key={index}
                                                        className="mt-2 text-xs text-muted-foreground"
                                                    >
                                                        {evidence.source}: “
                                                        {evidence.quote}”
                                                    </p>
                                                ),
                                            )}
                                        </div>
                                    ),
                                )}
                            </div>
                        </article>
                    ) : (
                        <div className="flex min-h-full items-center justify-center">
                            <div className="max-w-md text-center">
                                <div className="mx-auto mb-5 flex size-16 items-center justify-center rounded-2xl border bg-card text-primary shadow-sm">
                                    <Sparkles className="size-7" />
                                </div>
                                <h2 className="text-xl font-semibold">
                                    Draf berita akan muncul di sini
                                </h2>
                                <p className="mt-2 text-sm leading-6 text-muted-foreground">
                                    Tambahkan arahan, unggah hingga lima file,
                                    atau pilih informasi dan dokumen tersimpan.
                                </p>
                                <Button
                                    variant="outline"
                                    className="mt-5"
                                    onClick={() => setPicker(true)}
                                >
                                    <FolderSearch />
                                    Pilih sumber
                                </Button>
                            </div>
                        </div>
                    )}
                </section>
            </div>
        </>
    );
}

